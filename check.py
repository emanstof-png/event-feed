#!/usr/bin/env python3
"""check.py: the mechanical half of RULES.md. Run before every commit; CI runs it on every push.
Exit 1 with a list of violations, or 0 and "OK".

    python check.py            # checks sources_methods.csv, PLAYBOOK.md, readers/, fetch.py
    python check.py --sheet    # also compares the live sheet to the snapshot (needs GOOGLE_SERVICE_ACCOUNT_JSON)
"""
import csv, importlib, os, py_compile, subprocess, sys

ALLOWED = {"ical", "api", "xhr", "rss", "html", "jsonld", "reader", "browser", "stealth", "recurring", "none", "human"}
NEEDS_FEED = {"ical", "api", "xhr", "rss", "recurring"}
MODULE = {"ical": "ical", "api": "api", "xhr": "api", "rss": "rss", "html": "html", "jsonld": "html", "reader": "html",
          "browser": "browser", "stealth": "browser", "recurring": "recurring"}
STATUS_PREFIX = ("LIVE", "RECURRING", "NEEDS BROWSER", "NEEDS HUMAN", "EMPTY", "UNTESTED", "PAUSED")
problems = []

def bad(row, msg):
    problems.append(f"row {row['row']} {row['name'][:40]}: {msg}")

def load():
    return list(csv.DictReader(open("sources_methods.csv", newline="", encoding="utf-8")))

def check_rows(rows):
    seen = set()
    for r in rows:
        m, feed, url, status = r["method"].strip(), r["feed_url"].strip(), r["url"].strip(), r["status"].strip()
        if r["name"] in seen: bad(r, "duplicate name")
        seen.add(r["name"])
        if m != m.lower() or m not in ALLOWED: bad(r, f"method '{m}' not in {sorted(ALLOWED)}")
        if not url.startswith("http"): bad(r, "URL (column B) is not http")
        if m in NEEDS_FEED and not feed: bad(r, f"method {m} needs a Feed URL / rule in J")
        if m in ("ical", "api", "xhr", "rss") and not feed.startswith("http"): bad(r, "feed must be an http URL")
        if m == "recurring":
            try:
                sys.path.insert(0, "."); from readers.recurring import read
                read({"name": r["name"], "url": url, "feed_url": feed}, 60)
            except Exception as e:
                bad(r, f"recurring rule does not parse: {e}")
        if m in ("browser", "stealth") and feed and not feed.startswith("http"): bad(r, "browser J must be a URL or blank")
        if m != "none" and not status.startswith(STATUS_PREFIX): bad(r, f"status must start with one of {STATUS_PREFIX}")
        if m == "none" and not status.startswith(("EMPTY", "NEEDS")): bad(r, "method none needs an EMPTY/NEEDS status saying why")
        if status.startswith("EMPTY") and len(status) < 12: bad(r, "EMPTY must say what was checked")
        if m in MODULE and f"readers/{MODULE[m]}.py" not in r["how"] and m != "recurring": bad(r, f"How to read (N) does not name readers/{MODULE[m]}.py")
        if m == "recurring" and "recurring" not in r["how"]: bad(r, "How to read (N) should say recurring")
        if m in ("browser", "stealth"):
            want = "J" if feed else "B"
            if f"renders {want}" not in r["how"]: bad(r, f"How to read (N) must say 'renders {want}' (browser reads J when J is a URL)")

def check_playbook(rows):
    if not os.path.exists("PLAYBOOK.md"):
        problems.append("PLAYBOOK.md missing"); return
    text = open("PLAYBOOK.md", encoding="utf-8").read()
    if "Generated by `sync_playbook.py`" not in text:
        problems.append("PLAYBOOK.md was not generated by sync_playbook.py")
    body = [l for l in text.splitlines() if l.startswith("| ") and l[2].isdigit()]
    if len(body) != len(rows):
        problems.append(f"PLAYBOOK.md has {len(body)} rows, sources_methods.csv has {len(rows)}; run python sync_playbook.py")
    for r, line in zip(rows, body):
        if f"| {r['method']} |" not in line:
            problems.append(f"PLAYBOOK row {r['row']} method differs from csv; run python sync_playbook.py"); break

def check_feed():
    """The last committed feed: every row has a date, a title and an http link."""
    if not os.path.exists("feed_test.csv"):
        return
    for i, r in enumerate(csv.DictReader(open("feed_test.csv", newline="", encoding="utf-8")), start=2):
        if not r.get("Link", "").startswith("http"): problems.append(f"feed_test.csv row {i} ({r.get('Source','')[:30]}): empty Link"); break
        if not r.get("Date") or not r.get("Title"): problems.append(f"feed_test.csv row {i}: missing Date or Title"); break


def check_code():
    for f in ["fetch.py", "sync_playbook.py", "check.py"] + [f"readers/{m}.py" for m in set(MODULE.values())] + ["readers/common.py", "readers/haiku.py"]:
        try: py_compile.compile(f, doraise=True)
        except Exception as e: problems.append(f"{f} does not compile: {e}")
    sys.path.insert(0, ".")
    for m in set(MODULE.values()):
        try: importlib.import_module(f"readers.{m}")
        except Exception as e: problems.append(f"readers/{m}.py does not import: {type(e).__name__}: {e}")
    for f in ["CLAUDE.md", "RULES.md", "readers/README.md", "requirements.txt", "briefs/SCOUT_VERIFY.md",
              "briefs/SCOUT_RENDER.md", "briefs/BLURB.md", "render_test.py", ".github/workflows/render.yml",
              ".github/workflows/weekly.yml", ".github/workflows/feedtest.yml", ".github/workflows/check.yml"]:
        if not os.path.exists(f): problems.append(f"{f} missing")
    import glob, re as _re
    for f in glob.glob("briefs/*.md"):   # RULES 12: scouts read committed files, never fetch live
        for n, line in enumerate(open(f, encoding="utf-8"), 1):
            if _re.search(r"\b(WebFetch|WebSearch)\b", line) and not _re.search(r"(?i)\b(do not|never|no live)\b", line):
                problems.append(f"{f}:{n} tells a scout to fetch live (RULES 12)")
    try:
        out = subprocess.run(["git", "grep", "-nE", r"(sk-ant-|\"private_key\")", "--", ".", ":!check.py"], capture_output=True, text=True)
        if out.stdout.strip(): problems.append("a secret-looking string is committed:\n" + out.stdout[:500])
    except Exception:
        pass

def check_sheet(rows):
    import json
    import gspread
    from google.oauth2.service_account import Credentials
    creds = Credentials.from_service_account_info(json.loads(os.environ["GOOGLE_SERVICE_ACCOUNT_JSON"]),
                                                  scopes=["https://www.googleapis.com/auth/spreadsheets.readonly"])
    sh = gspread.authorize(creds).open_by_key(os.environ.get("SHEET_ID", "1vDMP4n3bOBGGvwZ9PerbctPr4uGhiRvxu1cPv_QROYg"))
    vals = sh.worksheet("Sources").get_all_values()[1:]
    live = {r[0]: (r[8].lower(), r[9]) for r in vals if r and r[0].strip()}
    for r in rows:
        if r["name"] not in live: problems.append(f"{r['name']} in csv but not in sheet")
        elif live[r["name"]] != (r["method"], r["feed_url"]):
            problems.append(f"{r['name']}: sheet says {live[r['name']]}, csv says {(r['method'], r['feed_url'])}; run python sync_playbook.py --from-sheet")
    for n in live:
        if n not in {r["name"] for r in rows}: problems.append(f"{n} in sheet but not in csv")

if __name__ == "__main__":
    rows = load()
    check_rows(rows); check_playbook(rows); check_code(); check_feed()
    if "--sheet" in sys.argv:
        if os.environ.get("GOOGLE_SERVICE_ACCOUNT_JSON"): check_sheet(rows)
        else: print("(--sheet skipped: no GOOGLE_SERVICE_ACCOUNT_JSON)")
    if problems:
        print(f"{len(problems)} problem(s):"); print("\n".join(" - " + p for p in problems)); sys.exit(1)
    print(f"OK: {len(rows)} sources, playbook in sync, readers import")
